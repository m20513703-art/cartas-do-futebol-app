'use strict';
const assert = require('assert');
const d = require('./brazil-2026-data');
const seriesD = require('./brazil-2026-series-d-groups.json');
const cb = require('./brazil-2026-copa-brasil-entrants.json');
assert.deepStrictEqual(d.validate(), []);
assert.equal(d.stateClubs.DF['1ª Divisão'].join('|'), 'Brasiliense|Brasília|Capital|Ceilândia|Gama|Paranoá|Real Brasília|Samambaia|Sobradinho|ARUC');
assert.equal(d.stateClubs.AM['1ª Divisão'].length, 7);
assert(!d.stateClubs.AM['1ª Divisão'].includes('Amazonas FC'));
assert(!d.stateClubs.PE['2026/27 novo formato unificado (24 clubes)'].length);
assert.equal(d.stateSummary().length, 27);
assert.equal(Object.keys(seriesD).length, 16);
assert(Object.values(seriesD).every(g => g.length === 6));
assert.equal(Object.values(seriesD).flat().length, 96);
const copaEntrants = Object.values(cb).flat();
assert.equal(copaEntrants.length, 126, '2026 Copa do Brasil supplied list must contain 126 entries');
assert.equal(3 * 27 + 20 + 20 + 5, 126, 'user-supplied Copa do Brasil formula arithmetic');
const copaRules = d.formats.national['Copa do Brasil'];
assert.equal(copaRules.phaseCount, 9);
assert.equal(copaRules.phaseRulesLatestUserCorrection.R1, '28 clubes; jogos únicos.');
assert.equal(copaRules.phaseRulesLatestUserCorrection.R4, '26 classificados jogam entre si = 13 vencedores; o usuário diz que apenas os dois piores no ranking jogam entre si para produzir 12 classificados. Preservar exatamente esta formulação/lógica, sem simplificar ou alterar.');
assert.equal(copaRules.phaseRulesLatestUserCorrection.R9, 'Final.');
assert.equal(copaRules.libertadoresQualification.retainedRule, 'Champion qualifies directly for Libertadores; runner-up to pre-Libertadores.');
assert.equal(d.formats.national['Série D'].qualificationRules.stateLeagueSlots.SP, 4);
assert.equal(d.formats.national['Série D'].qualificationRules.stateLeagueSlots.allOtherStatesAndDF, 2);
assert.match(d.formats.national['Série D'].qualificationRules.knownInconsistency.status, /Pending clarification/);
assert.equal(d.formats.national['Série C'].relegated, 2);
assert(d.formats.unknowns.length >= 3);
console.log('Brazil 2026 data checks passed');
