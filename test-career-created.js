'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const app=fs.readFileSync('App.js','utf8');
const data=require('./brazil-2026-data');
const career=require('./career-club');
assert.match(app,/const chosenClub=customClubName\.trim\(\)/);
assert.match(app,/knownParticipant\(chosenClub\)/);
assert.match(app,/const div=lowestStateDivision\(state\)/);
assert.doesNotMatch(app,/Toque em um clube abaixo para selecioná-lo/);
assert.match(app,/startProgress\.eligibility=\{\.\.\.startProgress\.eligibility,serieD:false,C:false,B:false,A:false/);
assert.match(app,/startProgress\.nationalEntryPending=true/);
assert.match(app,/const qualified=!!currentProgress\.pendingEligibility\?\.serieD/);
const teams=data.clubs('SP',data.divisions('SP').at(-1));
const before=JSON.stringify(teams);const created=career.buildCustomClubCareer('MM Futebol de Teste','Cidade',teams);
assert.deepEqual(created.leagueTeams.filter(x=>x==='MM Futebol de Teste'),['MM Futebol de Teste']);
for(const name of teams)assert(created.leagueTeams.includes(name));
assert.equal(JSON.stringify(teams),before);
const nationals=data.nationalClubs;assert(nationals['Série A'].includes('Corinthians'));
assert(!Object.values(data.seriesDGroups).flat().includes('Corinthians'));
console.log('Career created club, lowest division and national entry guard checks passed.');
