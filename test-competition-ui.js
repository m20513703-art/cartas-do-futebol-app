'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const src=fs.readFileSync('App.js','utf8');
assert.match(src,/tab==='Competições'&&<>[\s\S]*?COMPETIÇÕES JOGÁVEIS/,'competitions must have a dedicated tab');
assert.match(src,/\['Início','Competições','Classificação','Elenco','Mercado'\]/,'navigation must clearly expose competitions separately');
const start=src.indexOf("{tab==='Classificação'&&<>");
const end=src.indexOf("{tab==='Elenco'",start);
const classification=src.slice(start,end);
assert.ok(start>=0&&end>start,'classification tab should be present');
assert.match(classification,/game\.league\.teams\.map/,'classification should show active career league table');
assert.doesNotMatch(classification,/Object\.entries\(game\.tournaments\|\|\{\}\)/,'other competition tables should not be piled into league classification');
console.log('Competition cards have a dedicated tab; classification shows only the current league table.');
