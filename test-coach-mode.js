'use strict';
const assert = require('node:assert/strict');
const coach = require('./coach-mode');
const roles = ['GOL','ZAG','ZAG','ZAG','LAT','MEI','MEI','MEI','ATA','ATA','ATA','GOL','LAT','ZAG','MEI','ATA'];
const players = roles.map((role,i)=>({id:`p${i}`,name:`Jogador${i}`,surname:'Fictício',role,ovr:60+i,energy:100}));
const market = [{id:'m1',name:'Atleta',surname:'Fictício',role:'ATA',ovr:75,price:400,wage:40}];
let g = coach.ensureManagerState({club:'MM FC',players,coins:1000,lineup:players.slice(0,11).map(p=>p.id)},()=>[]);
assert.equal(g.lineup.length,11); assert.equal(new Set(g.lineup).size,11); assert(coach.validStartingXI(g.players,g.lineup));
const repaired=coach.ensureManagerState({players,coins:1000,lineup:['p0','p11','p2','p3','p4','p5','p6','p7','p8','p9','p10']},()=>[]); assert(coach.validStartingXI(players,repaired.lineup));
g=coach.startMatch({...g,subsUsed:3}); assert.equal(g.subsUsed,0);
g=coach.swapStarter(g,'p1','p12'); assert(g.lineup.includes('p12')); assert(!g.lineup.includes('p1')); assert(coach.validStartingXI(g.players,g.lineup));
g=coach.substitute(g,'p2','p13',{matchLive:true,paused:true}); assert.equal(g.subsUsed,1); assert(g.lineup.includes('p13')); assert(!g.lineup.includes('p2'));
assert.throws(()=>coach.substitute(g,'p3','p14',{matchLive:true,pause:true}),/Pause/);
assert.throws(()=>coach.substitute({...g,subsUsed:5},'p3','p14',{matchLive:true,paused:true}),/Limite/);
assert.throws(()=>coach.substitute(g,'p3','p14',{matchLive:true,paused:true}),/mesma posição/);
assert.throws(()=>coach.substitute(g,'p3','p2',{matchLive:true,paused:true}),/não pode voltar/);
const withMarket={...g,transferMarket:market,coins:1000}; const bought=coach.signPlayer(withMarket,market[0]);
assert.equal(bought.coins,600); assert.equal(bought.players.length,17); assert.equal(bought.transferMarket.length,0);
assert.throws(()=>coach.signPlayer({...withMarket,coins:100},market[0]),/Saldo insuficiente/);
assert.throws(()=>coach.signPlayer({...withMarket,players:Array(30).fill({id:'x'})},market[0]),/Limite de 30/);
console.log('Coach mode rules passed.');
