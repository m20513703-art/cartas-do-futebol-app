'use strict';
const assert = require('node:assert/strict');
const coach = require('./coach-mode');
const roles = ['GOL','GOL','GOL','ZAG','ZAG','ZAG','ZAG','LAT','LAT','LAT','LAT','MEI','MEI','MEI','MEI','MEI','ATA','ATA','ATA','ATA','ATA','MEI','ZAG'];
const players = roles.map((role,i)=>({id:i,name:`Jogador${i}`,surname:'Fictício',role,ovr:60+i,energy:100}));
const market = [{id:'m1',name:'Atleta',surname:'Fictício',role:'ATA',ovr:75,price:400,wage:40}];
let g = coach.ensureManagerState({club:'MM FC',players,coins:1000,lineup:players.slice(0,11).map(p=>p.id)},()=>[]);
assert.equal(g.players.length,23,'all generated players must survive manager-state normalization');
assert(g.players.every((p,i)=>p.id===i),'numeric IDs must be preserved, not coerced or discarded');
assert.equal(g.lineup.length,11); assert.equal(new Set(g.lineup).size,11); assert(coach.validStartingXI(g.players,g.lineup));
const reopened=coach.ensureManagerState(JSON.parse(JSON.stringify(g)),()=>[]);
assert.equal(reopened.players.length,23,'save/reopen must retain the whole roster'); assert.deepEqual(reopened.lineup,g.lineup);
const repaired=coach.ensureManagerState({players,coins:1000,lineup:['wrong',11,2,3,4,5,6,7,8,9,10]},()=>[]); assert(coach.validStartingXI(players,repaired.lineup));
g=coach.startMatch({...g,subsUsed:3}); assert.equal(g.subsUsed,0);
g=coach.swapStarter(g,3,12); assert(g.lineup.includes(12)); assert(!g.lineup.includes(3)); assert(coach.validStartingXI(g.players,g.lineup));
g=coach.substitute(g,2,13,{matchLive:true,paused:true}); assert.equal(g.subsUsed,1); assert(g.lineup.includes(13)); assert(!g.lineup.includes(2));
assert.throws(()=>coach.substitute(g,3,14,{matchLive:true,pause:true}),/Pause/);
assert.throws(()=>coach.substitute({...g,subsUsed:5},3,14,{matchLive:true,paused:true}),/Limite/);
assert.throws(()=>coach.substitute(g,3,14,{matchLive:true,paused:true}),/mesma posição/);
assert.throws(()=>coach.substitute(g,3,2,{matchLive:true,paused:true}),/não pode voltar/);
const withMarket={...g,transferMarket:market,coins:1000}; const bought=coach.signPlayer(withMarket,market[0]);
assert.equal(bought.coins,600); assert.equal(bought.players.length,24); assert.equal(bought.transferMarket.length,0);
assert.throws(()=>coach.signPlayer({...withMarket,coins:100},market[0]),/Saldo insuficiente/);
assert.throws(()=>coach.signPlayer({...withMarket,players:Array(30).fill({id:'x'})},market[0]),/Limite de 30/);
console.log('Coach mode rules, generated numeric roster IDs, lineup and save/reopen passed.');
